const LangContext = createContext(null);

function initialLang() {
  try {
    const saved = localStorage.getItem('monotes.lang');
    if (saved === 'uk' || saved === 'en') return saved;
  } catch (e) { /* storage unavailable */ }
  return (navigator.language || '').startsWith('en') ? 'en' : 'uk';
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);
  const setLang = useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem('monotes.lang', l); } catch (e) { /* ignore */ }
    document.documentElement.lang = l;
  }, []);
  const t = useCallback((key) => dict[lang][key] ?? dict.en[key] ?? key, [lang]);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
